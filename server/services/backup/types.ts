import type { DatabaseSync } from 'node:sqlite';
import type { BackupVerificationReport } from './backupVerifier';

/**
 * Backup snapshot package format (V1.2 Batch 2A).
 *
 * The manifest is the only contract a future restore implementation needs. Its
 * format is versioned independently from the application version and from the
 * SQLite schema version.
 */
export const BACKUP_FORMAT = 'inkflow-backup';
export const BACKUP_FORMAT_VERSION = 1;

export const BACKUP_DATABASE_RELATIVE_PATH = 'database/knowledge_hub.sqlite';
export const BACKUP_MANIFEST_FILE_NAME = 'manifest.json';

/**
 * IDs generated by `backupService` (UTC ISO timestamp + 4 random bytes, with
 * characters that are invalid on some filesystems removed). Staging cleanup
 * only ever removes entries matching this shape, never arbitrary directories
 * that happen to live under `.staging/`.
 */
const BACKUP_SNAPSHOT_ID_RE = /^backup-\d{8}T\d{9}Z-[0-9a-f]{8}$/;

export function isBackupSnapshotId(value: string): boolean {
  return BACKUP_SNAPSHOT_ID_RE.test(value);
}

export type SnapshotMode = 'hardlink' | 'copy' | 'mixed';

export interface BackupFileEntry {
  /** POSIX path relative to the backup root, e.g. documents/doc_1/index.md */
  path: string;
  size: number;
  sha256: string;
}

export interface BackupDatabaseEntry {
  /** POSIX path relative to the backup root. */
  path: string;
  size: number;
  sha256: string;
}

export interface BackupManifest {
  format: typeof BACKUP_FORMAT;
  formatVersion: number;
  applicationVersion: string;
  createdAt: string;
  schemaVersion: number;
  database: BackupDatabaseEntry;
  files: BackupFileEntry[];
  /** Number of entries in `files` (the database is counted separately). */
  fileCount: number;
  /** Sum of `files[].size` (the database size is reported separately). */
  totalSize: number;
  snapshotMode: SnapshotMode;
  /** Always true for format v1: sessions are removed from the database copy. */
  sessionsExcluded: boolean;
}

export type BackupErrorCode =
  | 'BACKUP_MAINTENANCE_MODE'
  | 'BACKUP_RECOVERY_FAILED'
  | 'BACKUP_INCONSISTENT_STATE'
  | 'BACKUP_DATABASE_SNAPSHOT_FAILED'
  | 'BACKUP_DATABASE_VALIDATION_FAILED'
  | 'BACKUP_FILE_SNAPSHOT_FAILED'
  | 'BACKUP_MANIFEST_INVALID'
  | 'BACKUP_STAGING_FAILED'
  | 'BACKUP_UNSUPPORTED'
  | 'BACKUP_VERIFICATION_FAILED'
  | 'BACKUP_VERIFICATION_TARGET_INVALID';

export class BackupError extends Error {
  public readonly code: BackupErrorCode;
  public readonly details: Record<string, unknown> | undefined;

  constructor(
    code: BackupErrorCode,
    message: string,
    details?: Record<string, unknown>,
    options?: { cause?: unknown }
  ) {
    super(message, options);
    this.name = 'BackupError';
    this.code = code;
    this.details = details;
  }
}

/** Injectable filesystem/database operations (defaults are production safe). */
export interface CreateBackupOptions {
  /**
   * Opt into hardlink-first snapshots (with copy fallback).
   *
   * Default: false. A backup must be an independent copy. Hardlinked snapshots
   * share inodes with the production files, so any in-place modification of a
   * source file (a text editor, `>` redirection, `rsync --inplace`, a sync tool,
   * or a future writer that truncates instead of renaming) would corrupt the
   * backup and the live file at the same time. Hardlinks are therefore a fast
   * mode, not an independent or immutable backup.
   */
  useHardlinks?: boolean;
  /**
   * @deprecated Use `useHardlinks` instead. When true, always forces copy mode.
   */
  forceCopy?: boolean;
  /** Test/diagnostic injection; defaults to fs.link. */
  linkFile?: (source: string, destination: string) => Promise<void>;
  /** Test/diagnostic injection; defaults to fs.copyFile with COPYFILE_EXCL. */
  copyFile?: (source: string, destination: string) => Promise<void>;
  /** Test/diagnostic injection; defaults to node:sqlite backup(). */
  backupDatabase?: (source: DatabaseSync, destination: string) => Promise<number>;
  /**
   * Test/diagnostic hook invoked after the manifest has been written and before
   * the staged snapshot is re-read and verified for publication. Production
   * callers never set it.
   */
  beforePublishVerification?: (stagingDir: string, manifest: BackupManifest) => Promise<void>;
  /** Test/diagnostic hook: runs after source pre-checks and before open/link. */
  beforeSourceOpen?: (relativePath: string, absolutePath: string) => Promise<void>;
  /** Test/diagnostic hook: runs after each copied 64 KiB chunk. */
  afterSourceCopyChunk?: (relativePath: string, bytesReadTotal: number) => Promise<void>;
}

export interface BackupSnapshotResult {
  id: string;
  /** Absolute path of the completed snapshot directory. */
  directory: string;
  manifestPath: string;
  manifest: BackupManifest;
  /**
   * Result of the pre-publication verification. The same report shape is
   * returned by `verifyBackupSnapshot()` for published backups; it records the
   * effective snapshotMode and any hardlink warning.
   */
  verification: BackupVerificationReport;
}
